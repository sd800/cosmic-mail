#!/usr/bin/env python3
"""Create a few KiB of synthetic display/encoding fixtures; never reads private mail."""
from pathlib import Path
from email.message import EmailMessage

folder = Path(__file__).resolve().parent.parent / 'test-dist' / 'mail-review'
folder.mkdir(parents=True, exist_ok=True)
mail = EmailMessage()
mail['Subject'] = 'A letter, with its layout intact'
mail['From'] = 'Reading Group <group@example.edu>'
mail['To'] = 'Reader <reader@example.edu>'
mail['Date'] = 'Wed, 21 Oct 2026 12:00:00 +0800'
mail.set_content('An HTML layout fixture with a red reply and an attached message.')
mail.add_alternative('''<html><head><style>
.letter {width:540px;background-color:#f7f4ed;font-family:Georgia,serif}
.title {font-size:25px;color:#193047} .reply {color:#b01f32;border-top:1px solid #999999;padding-top:16px}
@media (max-width: 600px) {.letter {width:100%}}
</style></head><body><div style="display:none">Hidden preheader &zwnj;&zwnj;</div>
<table class="letter" cellpadding="24" cellspacing="0" border="0"><tr><td>
<p class="title">A little room to read.</p><p>Don&rsquo;t lose the details &hellip; a caf&eacute;, a reply, a familiar font.</p>
<table width="100%" cellpadding="8" border="0"><tr><td width="50%"><b>First column</b><br>Layout without a grid.</td>
<td width="50%"><b>Second column</b><br>Spacing belongs to this message.</td></tr></table>
<p class="reply">A red reply stays distinct from the earlier message.</p>
<p><a href="https://example.edu/">Website</a> / <a href="mailto:reader@example.edu">Email</a> /
<a href="tel:+12015551234">Telephone</a> / <a href="sms:+12015551234">Message</a></p>
<img src="https://example.edu/never-load.png" alt="Remote image remains blocked">
</td></tr></table></body></html>''', subtype='html')
child = EmailMessage(); child['Subject'] = 'Attached reading notes'; child['From'] = 'Reader <reader@example.edu>'
child.set_content('An attached message can be read without saving it first.')
mail.add_attachment(child)
(folder / 'Layout.eml').write_bytes(mail.as_bytes())
(folder / 'Chinese.eml').write_bytes(
    b'Subject: =?UTF-8?B?5L0=?= =?UTF-8?B?oOWlvQ==?=\r\n'
    b'From: reader@example.edu\r\nContent-Type: text/plain; charset=gb2312\r\n\r\n'
    + '你好，鎔。'.encode('gbk') + b'\xff' + ' 后面的文字保留。'.encode('gbk')
)
(folder / 'Fragments.eml').write_bytes(
    b'Subject: Multiple body fragments\nContent-Type: multipart/mixed; boundary=x\n\n'
    b'--x\nContent-Type: text/html\n\n<p>Before the attachment.</p>\n'
    b'--x\nContent-Type: application/octet-stream\nContent-Disposition: attachment; filename=sample.txt\n\nTiny sample\n'
    b'--x\nContent-Type: text/html\n\n<form><button><p>After the attachment, despite unclosed inert wrappers.</p>\n--x--\n'
)
(folder / 'README.md').write_text('''# Message review fixtures

Generated by `python3 scripts/make-review-fixtures.py`; all content is synthetic.

- `Layout.eml`: safe colors/fonts, a responsive newsletter layout, nested borderless tables, hidden preheader, copy-only links, a blocked remote image, and an attached message.
- `Chinese.eml`: a split UTF-8 subject, GB2312 label with GBK text, one illegal byte, and valid text following it.
- `Fragments.eml`: HTML before/after an attachment and unclosed inert wrappers.

MSG codepages, FILETIME, nested storage, and unavailable attachment records use the tiny in-memory CFB builder in `Tests/MailCoreTests/MailCoreTests.swift`. Streaming export uses small chunks and cancellation, not a large disk file. The WebKit test checks computed layout, colors, hidden content, responsive width, and resource isolation.

Do not store real mail, full logs, or recordings here.
''')
